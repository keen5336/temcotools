import assert from "node:assert/strict";
import { createHmac, randomUUID } from "node:crypto";
import test from "node:test";
import bcrypt from "bcryptjs";
import { AuthError, SESSION_MS } from "../../lib/auth/policy";

const database = process.env.AUTH_TEST_DATABASE_URL;
test("PostgreSQL account migration, recovery, durable sessions and administrative boundaries", { skip: !database }, async t => {
  const target = new URL(database!);
  assert.equal(target.hostname, "127.0.0.1"); assert.equal(target.port, "55476"); assert.equal(target.pathname, "/auth_qa");
  process.env.DATABASE_URL = database;
  process.env.SESSION_SECRET = "synthetic-auth-test-session-secret-long-enough";
  const { prisma } = await import("../../lib/db");
  const identity = await import("../../lib/auth/identity");
  const { resolveSession, livePasswordSession } = await import("../../lib/auth/sessions");
  const admin = await import("../../lib/auth/admin");
  const { authBudget, authContext, sameOrigin, readAuthBody } = await import("../../lib/auth/context");
  const runId = randomUUID();
  const context = { source: `synthetic-test-${runId}` };
  const makeUser = async (name: string, role: "user" | "admin" = "user") => prisma.user.create({ data: { id: `auth-qa-${runId}-${name}`, username: `auth-qa-${runId}-${name}`, displayName: name, role, pinHash: await bcrypt.hash("1234", 4) } });
  const actor = (row: { id: string; userId: string; authVersion: number }) => resolveSession({ sessionId: row.id, userId: row.userId, authVersion: row.authVersion });
  const owner = await makeUser("admin", "admin"), staff = await makeUser("staff");
  const password = "Synthetic cedar trail 17";
  let adminSession: Awaited<ReturnType<typeof actor>>, staffSession: Awaited<ReturnType<typeof actor>>;
  let staffRow: Awaited<ReturnType<typeof identity.signInPassword>>;
  try {
    await t.test("legacy cookies and PINs provide no operational or administrative authority", async () => {
      const forged = await resolveSession({ userId: staff.id, role: "admin", isActive: true });
      assert.ok(!forged.userId && forged.upgradeRequired); assert.equal(forged.upgradeUsername, staff.username);
      await assert.rejects(admin.listManagedUsers(forged), /updated account/);
      const row = await identity.signInLegacy({ username: staff.username, pin: "1234" }, context);
      const restricted = await actor(row);
      assert.ok(!restricted.userId && restricted.upgradeRequired);
      assert.ok(!await livePasswordSession(row.id));
      await assert.rejects(identity.issueAccountCode(restricted, { userId: staff.id, purpose: "enroll", operationId: randomUUID(), reason: "synthetic verify" }));
      await assert.rejects(identity.issueOperatorCode(staff.id, "enroll", "synthetic verify"), /administrator/);
    });
    await t.test("first administrator requires offline independent enrollment; failed delivery rolls back", async () => {
      await assert.rejects(identity.issueOperatorCode(owner.id, "enroll", "synthetic bootstrap", async () => { throw new Error("synthetic file failure"); }), /file failure/);
      assert.equal(await prisma.accountCode.count({ where: { userId: owner.id } }), 0);
      const code = await identity.issueOperatorCode(owner.id, "enroll", "synthetic bootstrap");
      const stored = await prisma.accountCode.findUniqueOrThrow({ where: { id: code.id } });
      assert.ok(stored.tokenHash !== code.code && !JSON.stringify(stored).includes(code.code!));
      const row = await identity.completeAccountUpdate({ username: owner.username, code: code.code, password }, context);
      adminSession = await actor(row); assert.equal(adminSession.role, "admin");
      await assert.rejects(identity.completeAccountUpdate({ username: owner.username, code: code.code, password }, context), /invalid or expired/);
    });
    await t.test("one-use staff setup preserves identity/history and permanently disables old PIN", async () => {
      await prisma.user.update({ where: { id: staff.id }, data: { favoriteToolIds: ["pick-wave"] } });
      const request = { userId: staff.id, purpose: "enroll", operationId: randomUUID(), reason: "verified synthetic staff" };
      const code = await identity.issueAccountCode(adminSession, request);
      const replay = await identity.issueAccountCode(adminSession, request);
      assert.ok(replay.alreadyIssued && replay.code === null);
      await assert.rejects(identity.completeAccountUpdate({ username: owner.username, code: code.code, password }, context), /invalid or expired/);
      const input = { username: staff.username, code: code.code, password, deviceName: "Assigned Zebra" };
      const results = await Promise.allSettled([identity.completeAccountUpdate(input, context), identity.completeAccountUpdate(input, context)]);
      const accepted = results.filter(result => result.status === "fulfilled");
      assert.equal(accepted.length, 1); assert.equal(results.filter(result => result.status === "rejected").length, 1);
      staffRow = (accepted[0] as PromiseFulfilledResult<typeof staffRow>).value; staffSession = await actor(staffRow);
      assert.equal(staffSession.userId, staff.id); assert.equal(staffSession.role, "user");
      assert.ok(Math.abs(staffRow.expiresAt.getTime() - staffRow.createdAt.getTime() - SESSION_MS) < 1000);
      const saved = await prisma.user.findUniqueOrThrow({ where: { id: staff.id } });
      assert.deepEqual(saved.favoriteToolIds, ["pick-wave"]);
      assert.ok(saved.passwordEnrolledAt && saved.legacyDisabledAt && !saved.pinHash.startsWith("$2"));
      await assert.rejects(identity.signInLegacy({ username: staff.username, pin: "1234" }, context));
      assert.ok(!(await resolveSession({ userId: staff.id, isActive: true, role: "admin" })).userId);
      // Lost enrollment response is recoverable by normal password login.
      const signed = await identity.signInPassword({ username: staff.username, password }, context);
      assert.ok((await actor(signed)).userId);
      await admin.setLegacyLoginPolicy(adminSession, false);
      await admin.setLegacyLoginPolicy(adminSession, true);
      await assert.rejects(identity.signInLegacy({ username: staff.username, pin: "1234" }, context));
    });
    await t.test("expiry, revocation and current database identity override cookie claims", async () => {
      assert.equal((await resolveSession({ ...staffSession, role: "admin" })).role, "user");
      await prisma.authSession.update({ where: { id: staffRow.id }, data: { createdAt: new Date(Date.now() - 48 * 60 * 60_000) } });
      assert.ok((await actor(staffRow)).userId, "cross-shift inactivity does not expire the session");
      await prisma.authSession.update({ where: { id: staffRow.id }, data: { expiresAt: new Date(Date.now() - 1) } });
      assert.ok(!(await actor(staffRow)).userId);
      staffRow = await identity.signInPassword({ username: staff.username, password }, context); staffSession = await actor(staffRow);
      await identity.revokeAuthSession(staffRow.id, staff.id);
      assert.ok(!await livePasswordSession(staffRow.id)); assert.ok(!(await actor(staffRow)).userId);
      staffRow = await identity.signInPassword({ username: staff.username, password }, context); staffSession = await actor(staffRow);
      const before = (await prisma.user.findUniqueOrThrow({ where: { id: staff.id } })).authVersion;
      await admin.updateManagedUser(adminSession, staff.id, { expectedAuthVersion: before, role: "manager" });
      assert.ok(!(await actor(staffRow)).userId);
      await assert.rejects(admin.updateManagedUser(adminSession, staff.id, { expectedAuthVersion: before, isActive: false }), /changed/);
      staffRow = await identity.signInPassword({ username: staff.username, password }, context); staffSession = await actor(staffRow);
      assert.equal(staffSession.role, "manager");
      await assert.rejects(admin.listManagedUsers(staffSession), /Administrator/);
    });
    await t.test("recovery immediately blocks old credentials, all sessions and old PIN forever", async () => {
      const code = await identity.issueAccountCode(adminSession, { userId: staff.id, purpose: "reset", operationId: randomUUID(), reason: "verified synthetic recovery" });
      assert.ok(!(await actor(staffRow)).userId);
      await assert.rejects(identity.signInPassword({ username: staff.username, password }, context));
      await assert.rejects(identity.signInLegacy({ username: staff.username, pin: "1234" }, context));
      const next = "Synthetic new cedar trail 21";
      staffRow = await identity.completeAccountUpdate({ username: staff.username, code: code.code, password: next }, context); staffSession = await actor(staffRow);
      await assert.rejects(identity.completeAccountUpdate({ username: staff.username, code: code.code, password: next }, context));
      const second = await identity.signInPassword({ username: staff.username, password: next, deviceName: "Laptop" }, context);
      await identity.revokeOwnDevices(staffSession, null); assert.ok(!await livePasswordSession(second.id)); assert.ok(await livePasswordSession(staffRow.id));
      const changed = await identity.changeOwnPassword(staffSession, { currentPassword: next, password: "Synthetic third cedar trail 31" }, context);
      assert.ok(!await livePasswordSession(staffRow.id)); assert.ok(await livePasswordSession(changed.id));
    });
    await t.test("admin step-up, last usable admin and forbidden PIN writes are enforced server-side", async () => {
      await assert.rejects(identity.issueAccountCode(adminSession, { userId: owner.id, purpose: "reset", operationId: randomUUID(), reason: "test last admin" }), /another active administrator/);
      await assert.rejects(admin.updateManagedUser(adminSession, owner.id, { expectedAuthVersion: adminSession.authVersion, isActive: false }), /another active administrator/);
      await assert.rejects(admin.updateManagedUser(adminSession, staff.id, { expectedAuthVersion: 1, pin: "1234" }), /PIN sign-in cannot be restored/);
      await prisma.authSession.update({ where: { id: adminSession.sessionId }, data: { reauthenticatedAt: new Date(Date.now() - 11 * 60_000) } });
      await assert.rejects(admin.createManagedUser(adminSession, { username: `auth-qa-${runId}-new`, displayName: "New" }), /Confirm your password/);
      await identity.reauthenticate(adminSession, password, context);
      const created = await admin.createManagedUser(adminSession, { username: `auth-qa-${runId}-new`, displayName: "New" });
      const newUser = await prisma.user.findUniqueOrThrow({ where: { id: created.id } });
      assert.ok(!newUser.passwordHash && newUser.legacyDisabledAt && newUser.pinHash.startsWith("disabled:"));
      const code = await identity.issueAccountCode(adminSession, { userId: created.id, purpose: "enroll", operationId: randomUUID(), reason: "expiry negative fixture" });
      await prisma.accountCode.update({ where: { id: code.id }, data: { expiresAt: new Date(Date.now() - 1) } });
      await assert.rejects(identity.completeAccountUpdate({ username: created.username, code: code.code, password }, context), /invalid or expired/);
      await assert.rejects(identity.issueOperatorCode(owner.id, "reset", "delivery rollback", async () => { throw new Error("synthetic reset failure"); }));
      assert.ok(await livePasswordSession(adminSession.sessionId!), "failed reset delivery does not sign the admin out");
    });
    await t.test("persistent concurrent rate limits and HTTP origin/body bounds", async () => {
      const kind = `parallel-${runId}`;
      const results = await Promise.allSettled(Array.from({ length: 14 }, () => authBudget(kind, "qa-account", { source: "qa-limiter" })));
      assert.equal(results.filter(r => r.status === "fulfilled").length, 12);
      assert.equal(results.filter(r => r.status === "rejected" && r.reason instanceof AuthError && r.reason.status === 429).length, 2);
      const keys = [`${kind}:account:qa-account`, `${kind}:source:qa-limiter`].map(value => createHmac("sha256", process.env.SESSION_SECRET!).update(value).digest("hex"));
      assert.equal(await prisma.authRateLimit.count({ where: { key: { in: keys }, attempts: 14 } }), 2);
      const url = "https://temco.example/api/auth/login";
      process.env.NEXT_PUBLIC_APP_URL = "https://temco.example";
      assert.throws(() => sameOrigin(new Request(url)), /Same-origin/);
      assert.throws(() => sameOrigin(new Request(url, { headers: { origin: "https://evil.example" } })), /Same-origin/);
      assert.doesNotThrow(() => sameOrigin(new Request(url, { headers: { origin: "https://temco.example" } })));
      await assert.rejects(readAuthBody(new Request(url, { method: "POST", body: "x".repeat(12001) })), /too large/);
      await assert.rejects(readAuthBody(new Request(url, { method: "POST", body: "[]" })), /Invalid/);
      process.env.TRUST_PROXY = "true";
      assert.equal(authContext(new Request(url, { headers: { "x-forwarded-for": "spoofed, 10.1.1.7" } })).source, "10.1.1.7");
      delete process.env.TRUST_PROXY;
      assert.equal(authContext(new Request(url, { headers: { "x-forwarded-for": "spoofed" } })).source, "direct");
    });
  } finally { await prisma.user.deleteMany({ where: { username: { startsWith: `auth-qa-${runId}-` } } }); await prisma.$disconnect(); }
});
